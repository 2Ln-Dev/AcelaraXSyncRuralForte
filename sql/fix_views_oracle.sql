-- Fix V_AX_PRODUTOS: dedup by CODI_PSV
CREATE OR REPLACE VIEW V_AX_PRODUTOS AS
SELECT ps.CODI_PSV,
       MIN(ps.DESC_PSV)  AS DESC_PSV,
       MIN(ps.UNID_PSV)  AS UNID_PSV,
       MIN(ps.COMP_PSV)  AS COMP_PSV,
       MIN(ag.CODI_GPR)  AS CODI_GPR,
       MIN(ag.DESC_GPR)  AS DESC_GPR,
       MIN(ps.CODI_SBG)  AS CODI_SBG
FROM PRODSERV ps
LEFT JOIN (
    SELECT TO_NUMBER(SUBSTR(CHAVEGRUPO, 1, INSTR(CHAVEGRUPO,'#')-1)) AS CODI_GPR,
           MIN(DESC_GPR) AS DESC_GPR
    FROM APEX_GRUPO
    WHERE INSTR(CHAVEGRUPO,'#') > 0
    GROUP BY TO_NUMBER(SUBSTR(CHAVEGRUPO, 1, INSTR(CHAVEGRUPO,'#')-1))
) ag ON ag.CODI_GPR = ps.CODI_GPR
WHERE ps.SITU_PSV IS NULL OR ps.SITU_PSV <> 'I'
GROUP BY ps.CODI_PSV
/

-- Fix V_AX_ESTOQUE: one row per (CODI_EMP, CODI_PSV_VINC) — most recent cycle
CREATE OR REPLACE VIEW V_AX_ESTOQUE AS
SELECT e.CODI_EMP,
       e.CODI_PSV_VINC,
       ps.DESC_PSV       AS DESC_PSV_VINC,
       e.QTE1_PRO,
       e.QTE2_PRO,
       e.VALOR_UNIT,
       e.EF,
       e.RDE,
       e.PCNR,
       e.PVNE,
       e.CF,
       e.VF,
       e.MT,
       e.DISPONIVEL,
       ps.UNID_PSV,
       ag.CODI_GPR,
       ag.DESC_GPR,
       ps.CODI_SBG,
       sg.DESC_SBG
FROM (
    SELECT e2.CODI_EMP, e2.CODI_PSV_VINC,
           e2.QTE1_PRO, e2.QTE2_PRO, e2.VALOR_UNIT,
           e2.EF, e2.RDE, e2.PCNR, e2.PVNE,
           e2.CF, e2.VF, e2.MT, e2.DISPONIVEL,
           ROW_NUMBER() OVER (
               PARTITION BY e2.CODI_EMP, e2.CODI_PSV_VINC
               ORDER BY e2.CODI_CIC DESC NULLS LAST
           ) AS rn
    FROM EST_CICLO_AF2 e2
    WHERE e2.CODI_PSV_VINC IS NOT NULL
) e
LEFT JOIN (
    SELECT CODI_PSV,
           MIN(DESC_PSV) AS DESC_PSV,
           MIN(UNID_PSV) AS UNID_PSV,
           MIN(CODI_GPR) AS CODI_GPR,
           MIN(CODI_SBG) AS CODI_SBG
    FROM PRODSERV
    WHERE SITU_PSV IS NULL OR SITU_PSV <> 'I'
    GROUP BY CODI_PSV
) ps ON ps.CODI_PSV = e.CODI_PSV_VINC
LEFT JOIN (
    SELECT TO_NUMBER(SUBSTR(CHAVEGRUPO, 1, INSTR(CHAVEGRUPO,'#')-1)) AS CODI_GPR,
           MIN(DESC_GPR) AS DESC_GPR
    FROM APEX_GRUPO
    WHERE INSTR(CHAVEGRUPO,'#') > 0
    GROUP BY TO_NUMBER(SUBSTR(CHAVEGRUPO, 1, INSTR(CHAVEGRUPO,'#')-1))
) ag ON ag.CODI_GPR = ps.CODI_GPR
LEFT JOIN SUBGRUPO sg ON sg.CODI_SBG = ps.CODI_SBG
WHERE e.rn = 1
/

